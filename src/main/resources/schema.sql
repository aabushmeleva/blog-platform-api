CREATE TABLE IF NOT EXISTS post
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    text        CLOB         NOT NULL,
    likes_count BIGINT       NOT NULL DEFAULT 0,
    image_name  VARCHAR(255),
    CONSTRAINT chk_post_likes_count CHECK (likes_count >= 0)
    );

CREATE TABLE IF NOT EXISTS post_tag
(
    post_id BIGINT      NOT NULL,
    name    VARCHAR(64) NOT NULL,
    CONSTRAINT pk_post_tag PRIMARY KEY (post_id, name),
    CONSTRAINT fk_post_tag_post FOREIGN KEY (post_id) REFERENCES post (id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_post_tag_name ON post_tag (name);

CREATE TABLE IF NOT EXISTS comment
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    text    CLOB   NOT NULL,
    CONSTRAINT fk_comment_post FOREIGN KEY (post_id) REFERENCES post (id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_comment_post_id ON comment (post_id);
